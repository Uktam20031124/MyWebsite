def _bullets(items) -> str:
    return "\n".join(f"- {i}" for i in items)


def deck(key: str) -> str:
    """Bitta darsning to'liq taqdimoti (``Topic.slides`` formatida)."""
    lesson = LESSONS[key]
    week, number, topic = next(
        (w, n, t)
        for w, m in enumerate(MODULES, start=1)
        for n, t in enumerate(m.topics, start=1)
        if t.key == key
    )
    lesson_no = (week - 1) * 3 + number
    homework = topic.homework.strip()
    slides = [
        f"# {topic.title}\nMinar AI Creator · {week}-hafta · {lesson_no}-dars · 60 daqiqa\n\n🛠 {lesson['tool']}",
        f"## 🎯 Bugun nima yaratamiz?\n!! {lesson['create']}\n\n> Dars oxirida javob beramiz: “Bugun nimani yaratdim?”",
        f"## 🤔 Kirish savoli\n!! {lesson['hook']}",
        f"## 💡 Yangi tushunchalar\n{_bullets(lesson['concepts'])}",
        f"## 🧑‍🏫 Ustoz demo: {lesson['demo_title']}\n```\n{lesson['demo']}\n```",
        f"## ⚖️ Yomon va yaxshi\n### ❌ Yomon\n{lesson['bad']}\n### ✅ Yaxshi\n{lesson['good']}",
        "## 🛠 Amaliyot · 25 daqiqa\n" + "\n".join(f"{i}. {s}" for i, s in enumerate(lesson["practice"], 1))
        + "\n:: timer 25",
        f"## 🏁 Challenge · 5 daqiqa\n!! {lesson['challenge']}\n:: timer 5",
        f"## 🛡 Eslab qoling\n!! {lesson['rule']}",
        f"## 🎤 Show & Tell\n2–3 o'quvchi ko'rsatadi: nima yaratdim, qanday prompt yozdim, nima qiyin bo'ldi?\n"
        f"### 🏠 Uyga vazifa\n{homework}",
        f"# Bugun nimani yaratdim? ✨\n{' · '.join(lesson['recap'])}\n\n“AI bilan gaplashma — AI yordamida yarat.”",
    ]
    return "\n---\n".join(slides)


SLIDES = {key: deck(key) for key in LESSONS}
